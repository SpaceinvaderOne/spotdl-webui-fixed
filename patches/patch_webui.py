async def download_song_with_retry(downloader: Any, song: Song) -> Any:
    """
    Download a single song, retrying once with the result filter disabled.

    The audio providers score every search hit against the Spotify metadata and
    drop anything below their match threshold. Obscure releases, remixes and
    tracks with long parenthesised titles regularly score below it, so a second
    pass that trusts the top audio provider hit recovers most failures without
    weakening matching for songs that already resolve correctly.

    ### Arguments
    - downloader: The client's downloader instance.
    - song: The song to download.

    ### Returns
    - The path of the downloaded file, or `None` when both attempts failed.
    """

    path: Optional[Path] = None

    try:
        _, path = await downloader.pool_download(song)
        if path is not None:
            return path
    except Exception as exception:
        app_state.logger.debug("First attempt failed for %s: %s", song.name, exception)

    providers = list(downloader.audio_providers)
    original = [provider.filter_results for provider in providers]

    try:
        for provider in providers:
            provider.filter_results = False

        app_state.logger.info(
            "Retrying without the result filter: %s", song.display_name
        )
        _, path = await downloader.pool_download(song)
    finally:
        for provider, value in zip(providers, original):
            provider.filter_results = value

    return path


def download_status_element(url: str, inner: str) -> str:
    """
    Build the element that replaces the download button for a given url.

    ### Arguments
    - url: The URL the download was requested for.
    - inner: Markup to render inside the button.

    ### Returns
    - HTML string carrying the same element ID as the original button.
    """

    return (
        f'<button id="download-{html.escape(url, quote=True)}" '
        f'class="btn btn-primary btn-square normal-case">'
        f"{inner}</button>"
    )


async def _drain(updates) -> None:
    """
    Drive an SSE generator to completion, discarding what it yields.

    For work that has to outlive the request that started it. The payloads were
    addressed to that request, which is gone; what the user still needs - track
    by track progress - reaches the downloads page through the client's progress
    tracker regardless. Errors are logged rather than raised, because there is
    no longer a request that could report them.
    """
    try:
        async for _ in updates:
            pass
    except asyncio.CancelledError:
        raise
    except Exception as exception:
        app_state.logger.error(
            f"Background download failed: {exception}", exc_info=True
        )


